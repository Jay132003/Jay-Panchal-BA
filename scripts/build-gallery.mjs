// Turns Jay's original photos into small web images for the Gallery and writes
// src/data/gallery.ts. Run after adding photos:  node scripts/build-gallery.mjs
//
// Originals live in photos-originals/ (git-ignored, never shipped); anything in
// photos-originals/hidden/ is skipped. Each photo gets two JPEGs in
// public/assets/gallery/, named after the original: `<name>-sm.jpg` (strips,
// ~520px) and `<name>.jpg` (lightbox, ~1400px). Copies of photos that are gone
// or hidden are deleted. The date comes from the filename
// (20260115_182653.jpg, IMG20240615095028.heic, PXL_20241028_…, IMG-20250219-WA…).
// macOS only — uses the built-in `sips`, which also reads HEIC.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { extname, join, basename } from 'node:path';

const SRC = 'photos-originals';
const OUT = 'public/assets/gallery';
const DATA = 'src/data/gallery.ts';

mkdirSync(OUT, { recursive: true });

const sips = (...args) => execFileSync('sips', args, { encoding: 'utf8' });
const size = (file) => {
  const out = sips('-g', 'pixelWidth', '-g', 'pixelHeight', file);
  return { w: Number(/pixelWidth: (\d+)/.exec(out)[1]), h: Number(/pixelHeight: (\d+)/.exec(out)[1]) };
};

const photos = readdirSync(SRC)
  .filter((f) => /\.(jpe?g|heic|png)$/i.test(f))
  .map((file) => {
    const m = /(20[12]\d)[-_]?(0[1-9]|1[0-2])[-_]?(0[1-9]|[12]\d|3[01])/.exec(file);
    const date = m ? `${m[1]}-${m[2]}-${m[3]}` : '';
    // Undated shots (Snapchat, WhatsApp saves…) go last, in filename order.
    return { file, date, key: `${date || '9999'}|${file}` };
  })
  .sort((a, b) => a.key.localeCompare(b.key));

const entries = photos.map(({ file, date }) => {
  const name = basename(file, extname(file)).toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const src = join(SRC, file);
  const sm = join(OUT, `${name}-sm.jpg`);
  const lg = join(OUT, `${name}.jpg`);
  if (!existsSync(sm)) sips('-s', 'format', 'jpeg', '-s', 'formatOptions', '72', '-Z', '520', src, '--out', sm);
  if (!existsSync(lg)) sips('-s', 'format', 'jpeg', '-s', 'formatOptions', '70', '-Z', '1400', src, '--out', lg);
  const { w, h } = size(sm);
  return { src: `/assets/gallery/${name}-sm.jpg`, full: `/assets/gallery/${name}.jpg`, date, w, h };
});

const keep = new Set(entries.flatMap((e) => [basename(e.src), basename(e.full)]));
for (const f of readdirSync(OUT)) if (!keep.has(f)) rmSync(join(OUT, f));

writeFileSync(
  DATA,
  `// Generated by scripts/build-gallery.mjs — don't edit by hand; re-run the script.\n` +
    `import type { Photo } from './life';\n\n` +
    `export const photos: Photo[] = [\n` +
    entries
      .map((e) => `  { src: '${e.src}', full: '${e.full}', date: '${e.date}', w: ${e.w}, h: ${e.h} },`)
      .join('\n') +
    `\n];\n`,
);
console.log(`\n${entries.length} photos → ${OUT}, ${DATA}`);
