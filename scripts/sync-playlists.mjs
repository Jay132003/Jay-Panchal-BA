// Refreshes the turntable's playlist data from Spotify's public pages:
//   - src/data/playlistTracks.ts    (per playlist: songs with album art + 30s preview clip ids,
//                                    and each playlist's real song count)
//   - public/assets/playlists/*.jpg (640px playlist covers, used as a fallback)
// Run with: npm run playlists:sync
// Playlist ids + cover file names come from src/data/playlists.ts.

import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const playlistsSrc = await readFile(new URL('src/data/playlists.ts', root), 'utf8');

// Pull { id, cover } pairs out of the PLAYLISTS array.
const entries = [...playlistsSrc.matchAll(/id:\s*'([A-Za-z0-9]+)'[\s\S]*?cover:\s*'([^']+)'/g)].map(
  ([, id, cover]) => ({ id, cover }),
);
if (!entries.length) throw new Error('No playlists found in src/data/playlists.ts');

const NBSP = String.fromCharCode(160);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** fetch() that backs off and retries when Spotify rate-limits (429) or hiccups. */
async function fetchRetry(url, tries = 6) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0' } });
    if (res.ok || attempt >= tries || (res.status !== 429 && res.status < 500)) return res;
    const wait = Number(res.headers.get('retry-after')) * 1000 || 1500 * 2 ** (attempt - 1);
    await sleep(Math.min(wait, 30000));
  }
}

// Album art already fetched on a previous run, so re-syncs only look up new songs.
const knownArt = new Map();
try {
  const prev = await readFile(new URL('src/data/playlistTracks.ts', root), 'utf8');
  const data = JSON.parse(prev.slice(prev.lastIndexOf('= {') + 2).trim().replace(/;$/, ''));
  for (const list of Object.values(data)) for (const t of list) if (t[4]) knownArt.set(t[0], t[4]);
} catch {
  /* first run */
}

/** Album art id for a track via Spotify oEmbed (300px thumbnail → its 640px sibling). */
async function albumArt(trackId) {
  if (knownArt.has(trackId)) return knownArt.get(trackId);
  const res = await fetchRetry(`https://open.spotify.com/oembed?url=spotify:track:${trackId}`);
  if (!res.ok) return '';
  const hash = ((await res.json()).thumbnail_url ?? '').split('/image/').pop() ?? '';
  // ab67616d00001e02 = 300px album art; ab67616d0000b273 = the 640px version.
  return hash.replace(/^ab67616d00001e02/, 'ab67616d0000b273');
}

/** Real song count from the playlist page ("Playlist · Jay · 402 items"); the embed lists ≤100. */
async function totalSongs(id, fallback) {
  const html = await (await fetchRetry(`https://open.spotify.com/playlist/${id}`)).text();
  const n = Number(html.match(/(\d[\d,]*) (?:items|songs)/)?.[1]?.replace(/,/g, ''));
  return n > 0 ? n : fallback;
}

/** map() with a small concurrency limit so Spotify doesn't rate-limit us. */
async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: limit }, async () => {
      while (next < items.length) {
        const i = next++;
        out[i] = await fn(items[i]);
      }
    }),
  );
  return out;
}

const tracks = {};
const totals = {};
for (const { id, cover } of entries) {
  const html = await (await fetchRetry(`https://open.spotify.com/embed/playlist/${id}`)).text();
  const json = html.match(/<script id="__NEXT_DATA__" type="application\/json">([\s\S]*?)<\/script>/)?.[1];
  if (!json) throw new Error(`Couldn't read Spotify embed data for ${id}`);
  const entity = JSON.parse(json).props.pageProps.state.data.entity;

  tracks[id] = await mapLimit(entity.trackList, 3, async (t) => {
    const trackId = t.uri.split(':').pop();
    const preview = t.audioPreview?.url?.split('/mp3-preview/').pop() ?? '';
    const artists = t.subtitle.split(NBSP).join(' ');
    return [trackId, t.title, artists, t.duration, await albumArt(trackId), preview];
  });
  totals[id] = await totalSongs(id, tracks[id].length);

  const images = entity.visualIdentity?.image ?? entity.coverArt?.sources ?? [];
  const best = [...images].sort((a, b) => (b.maxWidth ?? b.width ?? 0) - (a.maxWidth ?? a.width ?? 0))[0];
  if (best?.url) {
    // Auto-generated 4-up mosaic covers only list a 300px size; 640 exists too.
    const url = best.url.replace('mosaic.scdn.co/300/', 'mosaic.scdn.co/640/');
    const img = Buffer.from(await (await fetch(url)).arrayBuffer());
    await writeFile(new URL(`public${cover}`, root), img);
  }
  const withArt = tracks[id].filter((t) => t[4]).length;
  const withPreview = tracks[id].filter((t) => t[5]).length;
  console.log(
    `${entity.name}: ${tracks[id].length} of ${totals[id]} songs ` +
      `(${withArt} with art, ${withPreview} with previews)${best?.url ? ', cover updated' : ''}`,
  );
}

const out = `/* Generated by scripts/sync-playlists.mjs from Spotify's public pages
 * (${new Date().toISOString().slice(0, 10)}). Don't edit by hand — run \`npm run playlists:sync\`.
 * id → [trackId, title, artists, durationMs, artId, previewId][] — album art lives at
 * https://i.scdn.co/image/<artId>, the 30s preview at https://p.scdn.co/mp3-preview/<previewId>.
 * Spotify's embed exposes at most the first 100 songs; PLAYLIST_TOTALS has the real counts. */
export type PlaylistTrack = [
  id: string,
  title: string,
  artists: string,
  durationMs: number,
  artId: string,
  previewId: string,
];

export const PLAYLIST_TOTALS: Record<string, number> = ${JSON.stringify(totals)};

export const PLAYLIST_TRACKS: Record<string, PlaylistTrack[]> = ${JSON.stringify(tracks)};
`;
await writeFile(new URL('src/data/playlistTracks.ts', root), out);
console.log('Wrote src/data/playlistTracks.ts');
